// 搜索文章
export function searchArticles(query: string, limit = 5): Article[] {
  const queryLower = query.toLowerCase()
  
  return PROFESSIONAL_ARTICLES.filter(article =>
    article.title.toLowerCase().includes(queryLower) ||
    article.summary.toLowerCase().includes(queryLower) ||
    article.tags.some(tag => tag.toLowerCase().includes(queryLower)) ||
    article.content.toLowerCase().includes(queryLower)
  ).slice(0, limit)
}

// 获取分类文章
export function getArticlesByCategory(category: Article['category']): Article[] {
  return PROFESSIONAL_ARTICLES.filter(a => a.category === category)
}

// 获取紧急文章
export function getEmergencyArticles(): Article[] {
  return PROFESSIONAL_ARTICLES.filter(a => a.severity === 'critical')
}